const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

export class Raw {
  constructor(value) {
    this.value = String(value);
  }

  toString() {
    return this.value;
  }
}

export const raw = (value) => new Raw(value);

export function esc(value) {
  return String(value).replace(/[&<>"']/g, (char) => ESCAPES[char]);
}

function interpolate(value) {
  if (value == null || value === false) return '';
  if (value instanceof Raw) return value.value;
  if (Array.isArray(value)) return value.map(interpolate).join('');
  return esc(value);
}

/** Template tag con escaping automatico. Usare raw() per HTML fidato. */
export function html(strings, ...values) {
  let out = strings[0];
  for (let i = 0; i < values.length; i += 1) {
    out += interpolate(values[i]) + strings[i + 1];
  }
  return new Raw(out);
}

export function setHTML(element, content) {
  if (!element) return;
  element.innerHTML = content instanceof Raw ? content.value : String(content ?? '');
}

export function cls(...values) {
  return values.filter(Boolean).join(' ');
}

